// 1. 일반적인 매개변수 사용 방식과 it 키워드 사용 방식
fun main() {
    val some1 = { no: Int -> println(no) } // 매개변수를 직접 선언한 람다 함수
    some1(10)
    val some2: (Int) -> Unit = { println(it) } // it 키워드를 사용한 람다 함수(매개변수가 하나이니 그냥 it으로 부르겠다)
    some2(20)
}

//람다함수: 익명 함수_함수를 값처럼(동작을 즉석에서 정의)
//고차함수: 함수를 매개변수로 받거나 변환
//object 클래스: 익명 클래스_하나의 객체를 만들어 공유
//컴패니언: 클래스에 공통 기능과 데이터를 소속시킴(객체를 생성하지 않고도 사용할 수 있도록)